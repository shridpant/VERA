#!/usr/bin/env python3
"""Render APPENDIX_RESULTS.md (Table A1 and companions) from analyzer outputs only. Never typed by hand.

    python appendix_table.py --run-dir experiments/experiment03B/runs/<run_id> [--seed 0] [--out FILE]
"""
import argparse
import json
from pathlib import Path


def fmt(v, nd=1):
    if v is None:
        return "NA"
    if isinstance(v, str):
        return v
    if isinstance(v, (list, tuple)):
        return f"{fmt(v[0], nd)} to {fmt(v[1], nd)}"
    return f"{v:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    rd = Path(a.run_dir)
    res = rd / "results"
    cfg = json.loads((rd / "frozen" / "config.json").read_text())
    t = json.loads((res / "table_a1.json").read_text())
    pr = json.loads((res / "primary.json").read_text())
    sec = json.loads((res / "secondary.json").read_text())
    val_p = rd / "validation" / "validation.json"
    val = json.loads(val_p.read_text()) if val_p.exists() else None
    led = [json.loads(l) for l in (rd / "ledger.jsonl").read_text().split("\n") if l.strip()] if (rd / "ledger.jsonl").exists() else []
    inputs = json.loads((rd / "inputs.json").read_text())["inputs"]
    L = []
    flags = pr.get("run_flags", {})
    if flags.get("partial") or flags.get("skipped_budget_lines"):
        L += [f"> **INCOMPLETE RUN.** The analysis ran on a partial run (partial={flags.get('partial')}, "
              f"budget-skipped request lines={flags.get('skipped_budget_lines')}). Estimates describe only the inputs "
              "that finished.", ""]
    if cfg["engine"] == "mock":
        L += ["> **SYNTHETIC RUN — NOT A RESULT.** This table was generated by the mock engine (an analytic scorer) to test",
              "> the table pipeline. No model was run. Do not cite any number below.", ""]
    L += [f"# experiment03B appendix results — run `{cfg['run_id']}`", "",
          f"Generated from `results/table_a1.json`, `results/primary.json` and `results/secondary.json` by "
          f"`code/appendix_table.py`. Protocol v{cfg['protocol_version']}. Engine: `{cfg['engine']}`.", ""]
    status = {}
    for i in inputs:
        status[i.get("status")] = status.get(i.get("status"), 0) + 1
    L += ["## Planned, executed and failed", "",
          f"- Inputs in this run: {len(inputs)} (status: {', '.join(f'{k} {v}' for k, v in sorted(status.items(), key=str))}).",
          f"- Baseline original alerts: {sec['baseline_alert_rate']['all_selected']}; baseline labels missing: "
          f"{sec['baseline_alert_rate']['L0_missing']}.",
          f"- Stages failed in the ledger: {sorted({e['stage'] for e in led if e['event'] == 'failed'}) or 'none'}.",
          f"- Independent validation: " + ("not run" if val is None else ("PASSED" if val.get("passed") else "FAILED")
                                           + f" ({sum(c.get('passed') is True for c in val.get('checks', []))} checks passed, "
                                             f"{sum(c.get('passed') is False for c in val.get('checks', []))} failed)"), ""]
    man_p = rd / "frozen" / "manifest.json"
    man = json.loads(man_p.read_text()) if man_p.exists() else {}
    if man.get("windows"):
        planned = {u["window_uid"] for u in man.get("unique_inputs", [])}
        have = {i["window_uid"] for i in inputs}
        by = {}
        for w in man["windows"]:
            by.setdefault(w["stratum"], {}).setdefault(w["status"], 0)
            by[w["stratum"]][w["status"]] += 1
        unavailable = sorted(w["video_id"] for w in man["windows"] if w["status"] == "unavailable")
        L += ["## Coverage (frozen manifest)", "",
              f"- Videos: {len(man.get('videos', []))} in the manifest "
              f"({sum(v.get('development', False) for v in man.get('videos', []))} development).",
              "- Window records by stratum and status: " + "; ".join(
                  f"{st}: " + ", ".join(f"{k} {v}" for k, v in sorted(d.items())) for st, d in sorted(by.items())) + ".",
              f"- Benchmark-negative records with no eligible window ({len(unavailable)}): {', '.join(unavailable) or 'none'}.",
              f"- Planned unique inputs: {len(planned)}; in this run: {len(have & planned)}; planned but never "
              f"retrieved or run: {len(planned - have)}.", ""]
    L += ["## Primary estimate (confirmation set)", ""]
    if pr["estimate_pp"] is None:
        L += ["No eligible confirmation input: NA. (The confirmation set excludes the development videos; "
              "see the sensitivity row.)", ""]
    else:
        st = pr["bootstrap"]["stability"]
        lo = [s["ci95_pp"][0] for s in st if s["ci95_pp"]]
        hi = [s["ci95_pp"][1] for s in st if s["ci95_pp"]]
        L += [f"Paired advantage of the blur-ranked top two over a uniformly random grey pair, in original-VERA "
              f"alert flips: **{fmt(pr['estimate_pp'])} pp (95% CI {fmt(pr['ci95_pp'])})**, "
              f"{pr['n_inputs'] - pr['n_inputs_missing_dw']} of {pr['n_inputs']} confirmation alert inputs with d_w, in "
              f"{pr['n_videos']} videos; video-cluster bootstrap, seed {pr['bootstrap']['seed']}, "
              f"{pr['bootstrap']['B']} resamples. Monte Carlo stability over seeds "
              f"{[s['seed'] for s in st]}: lower endpoint {fmt(min(lo)) if lo else 'NA'} to {fmt(max(lo)) if lo else 'NA'}, "
              f"upper {fmt(min(hi)) if hi else 'NA'} to {fmt(max(hi)) if hi else 'NA'}. Worst-case missing-data bounds: "
              f"{fmt(pr['bounds_pp'])} pp (these bound the estimate had every missing label been observed; the complete-case "
              f"estimate need not lie inside them).", ""]
    L += ["| Sensitivity | Estimate, pp | 95% CI | N videos | N inputs |", "|---|---:|---:|---:|---:|"]
    for k, v in pr["sensitivity"].items():
        L.append(f"| {k} | {fmt(v['estimate_pp'])} | {fmt(v['ci95_pp'])} | {v['n_videos']} | {v['n_inputs']} |")
    L += ["", "## Table A1. Prespecified appendix summary", "",
          "| Population | N videos | N windows | N alerts | N complete | Top-2 flip % | Random-pair flip % | "
          "Paired advantage, pp (95% CI) | Mean top-2 overlap, blur/grey |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for i, r in enumerate(t["rows"]):
        adv = r["paired_advantage_pp"]
        if isinstance(adv, (int, float)):
            adv = f"{adv:.1f} ({fmt(r['ci95_pp'])})" if isinstance(r["ci95_pp"], list) else f"{adv:.1f} (descriptive)"
        name = f"**{r['population']}**" if i == 0 else r["population"]
        L.append(f"| {name} | {r['n_videos']} | {r['n_windows']} | {r['n_alerts']} | {r['n_complete']} | "
                 f"{fmt(r['top2_flip_pct'])} | {fmt(r['random_pair_flip_pct'])} | {adv} | "
                 f"{fmt(r['mean_top2_overlap_blur_grey'], 2)} |")
    n = t["note"]
    L += ["", "*Table note.* " + "; ".join(f"{k.replace('_', ' ')}: {v}" for k, v in n.items()) + ". `NA` rows give no "
          "eligible complete alert; category and stratum rows are descriptive, not separate hypothesis tests.", ""]
    na = [r for r in t["rows"] if r.get("na_reason")]
    if na:
        L += ["NA reasons: " + "; ".join(f"{r['population']}: {r['na_reason']}" for r in na) + ".", ""]
    L += ["## Fixed versus adaptive grey prefixes (secondary)", "",
          "| Mode, k | Label-change rate (video-weighted) | Mean q·ΔS_hi | Inputs | Videos | Attributable new calls |",
          "|---|---:|---:|---:|---:|---:|"]
    for k, v in sec["2_fixed_vs_adaptive_grey_prefixes"].items():
        L.append(f"| {k} | {fmt(v['label_change_rate_video_weighted'], 3)} | {fmt(v['mean_q_dS_hi_video_weighted'], 3)} | "
                 f"{v['n_inputs']} | {v['n_videos']} | {v['attributable_new_calls']} |")
    L += ["", "Prompts used: `results/prompts/` (exact question strings for the original, no-sound and label-only "
          "targets, the no-sound diff, and a comparison with experiment02 run_002).",
          "", f"Secondary scope: `{sec.get('scope')}`. Companion files: `results/inputs_metrics.csv`, `results/pairs.csv`, "
          "`results/trajectories.csv` (native-BF16 sensitivity and fixed/adaptive k = 1..4), `results/secondary.json`.", "",
          "Regenerate: `setup/environment/env/bin/python experiments/experiment03B/code/run_workflow.py --config "
          f"<this run's frozen config> --run-id {cfg['run_id']} --resume --stages analysis validation report --seeds {a.seed}`", ""]
    out = Path(a.out) if a.out else res / "APPENDIX_RESULTS.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    main()
